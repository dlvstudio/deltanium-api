	[ApiController]
	[Route("api/policy")]
	public class PolicyController : ControllerBase
	{
		private static readonly string NoncePath = Path.Combine(
			Environment.GetFolderPath(Environment.SpecialFolder.UserProfile),
			".deltanium",
			"pre_nonce.json");
		private readonly IStorageService _storageService;
		private readonly SignatureAuthHelper _auth;
		private readonly IConfiguration _config;

		private record NonceRecord(string UserPubKey, string Nonce, DateTime Exp);

		public PolicyController(IStorageService storageService, SignatureAuthHelper auth, IConfiguration config)
		{
			_storageService = storageService;
			_auth = auth;
			_config = config;
		}

		[HttpGet("nonce")]
		public IActionResult GetNonce([FromQuery] string userPubKey)
		{
			if (string.IsNullOrWhiteSpace(userPubKey)) return BadRequest("userPubKey required");
			var nonce = Convert.ToBase64String(RandomNumberGenerator.GetBytes(32));
			var rec = new NonceRecord(userPubKey, nonce, DateTime.UtcNow.AddMinutes(5));
			var dir = Path.GetDirectoryName(NoncePath);
			if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
			System.IO.File.WriteAllText(NoncePath, JsonSerializer.Serialize(rec));
			return Ok(new { nonce, exp = rec.Exp });
		}

		[HttpPost("publish-tag")]
		public IActionResult PublishTag([FromBody] JsonElement body)
		{
			// Minimal accept; in real impl, verify signature headers
			var tag = body.TryGetProperty("tag", out var t) ? t.GetString() : null;
			var scheme = body.TryGetProperty("policyScheme", out var s) ? s.GetString() : null;
			if (string.IsNullOrWhiteSpace(tag) || string.IsNullOrWhiteSpace(scheme)) return BadRequest("tag and policyScheme required");
			return Ok(new { tag, policyScheme = scheme, ok = true });
		}

		/// <summary>
		/// Upload rekey generated by author A for follower B
		/// Called by author's app after generating rk(A→B) locally
		/// </summary>
		[HttpPost("upload-rekey")]
		public async Task<IActionResult> UploadRekey()
		{
			Request.EnableBuffering();
			using var reader = new StreamReader(Request.Body);
			var rawBody = await reader.ReadToEndAsync();
			Request.Body.Position = 0;

			var (ok, following, err) = await _auth.ValidateAsync(Request, rawBody);
			if (!ok) return Unauthorized(err);

			using var doc = JsonDocument.Parse(string.IsNullOrWhiteSpace(rawBody) ? "{}" : rawBody);
			var body = doc.RootElement;
			var follower = body.TryGetProperty("followerPubKey", out var fp) ? fp.GetString() : null;
			var tag = body.TryGetProperty("tag", out var tg) ? tg.GetString() : null;
			var rk = body.TryGetProperty("rk", out var rkJ) ? rkJ.GetString() : null;
			var scope = body.TryGetProperty("scope", out var sc) ? sc.GetString() : "tag";
			var fileId = body.TryGetProperty("fileId", out var fid) ? fid.GetString() : null;

			if (string.IsNullOrWhiteSpace(follower) || string.IsNullOrWhiteSpace(following) ||
			    string.IsNullOrWhiteSpace(tag) || string.IsNullOrWhiteSpace(rk))
				return BadRequest("Missing required fields: followerPubKey, tag, rk");

			var isFollower = await _storageService.IsFollowingAsync(follower, following);
			if (!isFollower)
				return BadRequest("Follower relationship does not exist");

			var rekey = new UserRekey
			{
				FollowingPubKey = following!,
				FollowerPubKey = follower,
				Tag = tag,
				Scope = scope!,
				FileId = fileId,
				RkBase64 = rk,
				CreatedAt = DateTime.UtcNow,
				IsActive = true
			};

			await _storageService.SaveRekeyAsync(rekey);
			return Ok(new { ok = true, message = "Rekey uploaded successfully" });
		}
		
		/// <summary>
		/// Batch upload multiple rekeys at once (for efficiency)
		/// </summary>
		[HttpPost("upload-rekeys-batch")]
		public async Task<IActionResult> UploadRekeysBatch()
		{
			try
			{
				Request.EnableBuffering();
				Request.Body.Position = 0;
				using var reader = new StreamReader(Request.Body);
				var rawBody = await reader.ReadToEndAsync();
				Request.Body.Position = 0;

				var (okAuth, following, authErr) = await _auth.ValidateAsync(Request, rawBody);
				if (!okAuth) return Unauthorized(authErr);

				Console.WriteLine($"[UPLOAD_REKEYS_BATCH] Request from: {following}");

				if (string.IsNullOrWhiteSpace(rawBody))
				{
					return BadRequest("Empty request body");
				}

				JsonDocument doc;
				try
				{
					doc = JsonDocument.Parse(rawBody);
				}
				catch (Exception ex)
				{
					Console.WriteLine($"[UPLOAD_REKEYS_BATCH] ERROR: Invalid JSON - {ex.Message}");
					return BadRequest("Invalid JSON body");
				}

				using (doc)
				{
					var root = doc.RootElement;
					if (root.ValueKind != JsonValueKind.Object)
					{
						Console.WriteLine($"[UPLOAD_REKEYS_BATCH] ERROR: Body root is not an object (ValueKind={root.ValueKind})");
						return BadRequest($"Invalid request body type: {root.ValueKind}");
					}

					if (!root.TryGetProperty("rekeys", out var rekeysArray) || rekeysArray.ValueKind != JsonValueKind.Array)
					{
						Console.WriteLine("[UPLOAD_REKEYS_BATCH] Missing or invalid 'rekeys' array");
						return BadRequest("Missing or invalid 'rekeys' array");
					}

					var rekeys = new List<UserRekey>();
					
                    foreach (var rekeyElement in rekeysArray.EnumerateArray())
                    {
						var follower = rekeyElement.TryGetProperty("followerPubKey", out var fp) ? fp.GetString() : null;
						var tag = rekeyElement.TryGetProperty("tag", out var tg) ? tg.GetString() : null;
						var rk = rekeyElement.TryGetProperty("rk", out var rkJ) ? rkJ.GetString() : null;
						var scope = rekeyElement.TryGetProperty("scope", out var sc) ? sc.GetString() : "tag";
						var fileId = rekeyElement.TryGetProperty("fileId", out var fid) ? fid.GetString() : null;
						
						if (string.IsNullOrWhiteSpace(follower) || string.IsNullOrWhiteSpace(tag) || string.IsNullOrWhiteSpace(rk))
							continue; // Skip invalid entries
						
						// Verify follower relationship
						var isFollower = await _storageService.IsFollowingAsync(follower, following);
						if (!isFollower)
							continue; // Skip non-followers
						
						rekeys.Add(new UserRekey
						{
							FollowingPubKey = following,
							FollowerPubKey = follower,
							Tag = tag,
							Scope = scope!,
							FileId = fileId,
							RkBase64 = rk,
							CreatedAt = DateTime.UtcNow,
							IsActive = true
						});
                    }

                    if (rekeys.Count == 0)
                    {
                        return BadRequest("No valid rekeys to upload");
                    }

                    await _storageService.SaveRekeysBatchAsync(rekeys);
				
				Console.WriteLine($"[UPLOAD_REKEYS_BATCH] Saved {rekeys.Count} rekeys for author: {following}");
				
                return Ok(new { ok = true, count = rekeys.Count, message = $"Uploaded {rekeys.Count} rekeys successfully" });
            }
        }
            catch (Exception ex)
			{
				Console.WriteLine($"[UPLOAD_REKEYS_BATCH] Error: {ex.Message}");
				Console.WriteLine($"[UPLOAD_REKEYS_BATCH] Stack trace: {ex.StackTrace}");
				return StatusCode(500, new { error = ex.Message });
			}
		}

		/// <summary>
		/// Fetch rekey for follower B to decrypt author A's content
		/// Returns cached rekey uploaded by author A (no generation here!)
		/// </summary>
		[HttpPost("fetch-rekey")]
		public async Task<IActionResult> FetchRekey()
		{
			try
			{
				var requester = Request.Headers["X-User-PubKey"].ToString(); // Follower B
				Request.EnableBuffering();
				Request.Body.Position = 0;
				using var reader = new StreamReader(Request.Body);
				var rawBody = await reader.ReadToEndAsync();
				Request.Body.Position = 0;

				if (string.IsNullOrWhiteSpace(rawBody))
					return BadRequest("Empty request body");

				using var doc = JsonDocument.Parse(rawBody);
				var root = doc.RootElement;
				var following = root.TryGetProperty("followingPubKey", out var fp) ? fp.GetString() : null;
				var tag = root.TryGetProperty("tag", out var tg) ? tg.GetString() : null;
				var mode = root.TryGetProperty("mode", out var md) ? md.GetString() : "client";
				var proof = root.TryGetProperty("proof", out var pr) ? pr : default;

				if (string.IsNullOrWhiteSpace(following) || string.IsNullOrWhiteSpace(tag) || string.IsNullOrWhiteSpace(requester))
					return BadRequest("Missing required fields: followingPubKey, tag");

				// Verify B follows A
				var isFollowing = await _storageService.IsFollowingAsync(requester, following);
				if (!isFollowing)
					return Unauthorized("You must be following this user to access their content");

				// Minimal PoP check
				if (proof.ValueKind == JsonValueKind.Object && System.IO.File.Exists(NoncePath))
				{
					var rec = JsonSerializer.Deserialize<NonceRecord>(System.IO.File.ReadAllText(NoncePath));
					if (rec == null || rec.UserPubKey != requester || rec.Exp < DateTime.UtcNow)
						return Unauthorized("Invalid or expired nonce");
				}

				var rekey = await _storageService.GetRekeyAsync(requester, following, tag);
				if (rekey == null)
				{
					return NotFound(new { error = "Rekey not available yet", following, tag });
				}
				if (!rekey.IsActive)
					return Unauthorized(new { error = "Rekey revoked" });

				if (string.Equals(mode, "client", StringComparison.OrdinalIgnoreCase))
					return Ok(new { rekey = rekey.RkBase64, scope = rekey.Scope, tag = rekey.Tag, fileId = rekey.FileId, exp = DateTime.UtcNow.AddMinutes(5) });

				var token = Convert.ToBase64String(Encoding.UTF8.GetBytes(JsonSerializer.Serialize(new
				{
					followingPubKey = following,
					followerPublicKey = requester,
					tag,
					scope = rekey.Scope,
					fileId = rekey.FileId,
					exp = DateTime.UtcNow.AddMinutes(5)
				})));
				return Ok(new { token });
			}
			catch (Exception ex)
			{
				return StatusCode(500, new { error = ex.Message });
			}
		}

		[HttpPost("validate-token")]
		public async Task<IActionResult> ValidateToken([FromBody] JsonElement body)
		{
			var expected = _config["InternalApi:Token"];
			if (string.IsNullOrWhiteSpace(expected) ||
			    !Request.Headers.TryGetValue("X-Internal-Token", out var provided) ||
			    !string.Equals(provided.FirstOrDefault(), expected, StringComparison.Ordinal))
			{
				return Unauthorized("Store/internal token required");
			}

			var token = body.TryGetProperty("token", out var tk) ? tk.GetString() : null;
			if (string.IsNullOrWhiteSpace(token)) return BadRequest("token required");
			try
			{
				var json = Encoding.UTF8.GetString(Convert.FromBase64String(token));
				var payload = JsonSerializer.Deserialize<JsonElement>(json);
				var following = payload.TryGetProperty("followingPubKey", out var f1) ? f1.GetString() : null;
				var follower = payload.TryGetProperty("followerPublicKey", out var f2) ? f2.GetString() : null;
				var tag = payload.TryGetProperty("tag", out var tg) ? tg.GetString() : null;
				var exp = payload.TryGetProperty("exp", out var ex) ? ex.GetDateTime() : DateTime.MinValue;
				if (exp < DateTime.UtcNow) return Unauthorized("token expired");
				
				// Get rekey from storage
				var rekey = await _storageService.GetRekeyAsync(follower, following, tag);
				if (rekey == null) return NotFound("rk not found");
				
				return Ok(new { rk = rekey.RkBase64, scope = rekey.Scope, tag = rekey.Tag, fileId = rekey.FileId, exp = DateTime.UtcNow.AddMinutes(5) });
			}
			catch (Exception ex)
			{
				return BadRequest(new { error = ex.Message });
			}
		}

	}
